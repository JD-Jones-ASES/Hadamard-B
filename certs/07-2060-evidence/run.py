    # the measurement
    print("\n[5] plain vs gist, per side, per implementation")
    print("      %-4s %-4s %10s %8s %9s %8s %14s"
          % ("impl", "side", "draws", "bins", "max|z|", "at |T4|", ">4sigma"))
