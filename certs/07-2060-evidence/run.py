def f2_rank(vectors):
    """Rank over F2 by highest-set-bit pivoting.  Exact, no floats."""
    piv = {}
    r = 0
    for v in vectors:
        while v:
            h = v.bit_length() - 1
            if h in piv:
                v ^= piv[h]
            else:
                piv[h] = v
                r += 1
                break
    return r


def dim_V_W(rows):
    """V = span{r_i + r_j} = span{r_i + r_0}; W = V + <all-ones>.

    Only dim W is a Hadamard-equivalence invariant: row negation sends
    r_i -> r_i + delta_i*1, so the stray all-ones terms live in W but move
    V.  See NOTE-B.md S3.1 trap 1, and cert 06 control C3, which exhibits
    the jump.
    """
    n = len(rows)
    f = []
    for r in rows:
        v = 0
        for c, ch in enumerate(r):
            if ch == "-":
                v |= 1 << c
        f.append(v)
    gens = [f[i] ^ f[0] for i in range(1, n)]
    ones = (1 << len(rows[0])) - 1
    return f2_rank(gens), f2_rank(gens + [ones])


