def is_hadamard(rows):
    n = len(rows)
    S = [[1 if ch == "+" else -1 for ch in r] for r in rows]
    if any(len(r) != n for r in S):
        return False
    for i in range(n):
        for j in range(i + 1, n):
            if sum(a * b for a, b in zip(S[i], S[j])) != 0:
                return False
    return True


def signed_and_abs_profile(rows):
    """(signed T4 histogram, |T4| histogram), by straight enumeration."""
    n = len(rows)
    S = [[1 if ch == "+" else -1 for ch in r] for r in rows]
    sg, ab = {}, {}
    for a in range(n):
        for b in range(a + 1, n):
            ab2 = [S[a][c] * S[b][c] for c in range(n)]
            for c_ in range(b + 1, n):
                abc = [ab2[c] * S[c_][c] for c in range(n)]
                for d in range(c_ + 1, n):
                    t = sum(abc[c] * S[d][c] for c in range(n))
                    sg[t] = sg.get(t, 0) + 1
                    ab[abs(t)] = ab.get(abs(t), 0) + 1
    return sg, ab


